def main() -> None:
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "ライブ講義スケジュール"

    ws["A1"] = "AI人材育成講座 ライブ講義スケジュール(サンプル・匿名化データ)"
    ws["A2"] = "※日程は変更になる場合があります。対象年は取込画面で指定してください。"

    start_row = 3
    for offset, (a, b, c, d, e) in enumerate(ROWS):
        r = start_row + offset
        ws.cell(row=r, column=1, value=a)
        ws.cell(row=r, column=2, value=b)
        ws.cell(row=r, column=3, value=c)
        ws.cell(row=r, column=4, value=d)
        ws.cell(row=r, column=5, value=e)

    for col, width in zip("ABCDE", [16, 22, 12, 22, 12]):
        ws.column_dimensions[col].width = width

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    wb.save(OUTPUT_PATH)
    print(f"作成しました: {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
